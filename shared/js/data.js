function seededRandom(seed) {
  let s = seed;
  return () => (s = (s * 9301 + 49297) % 233280) / 233280;
}
function buildPlan(sp, seed) {
  const rnd = seededRandom(seed * 17 + 5);
  const q = Math.round(sp.desks * (sp.quiet == null ? 0.5 : sp.quiet));
  sp.plan = [];
  for (let k = 0; k < sp.desks; k++) {
    const id = "T" + String(k + 1).padStart(2, "0");
    sp.plan.push({
      id,
      zone: k < q ? "quiet" : "social",
      base: sp.busyIds ? sp.busyIds.includes(id) : rnd() < (sp.load == null ? 0.4 : sp.load),
    });
  }
}
